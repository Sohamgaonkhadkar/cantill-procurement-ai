import { test, expect } from "@playwright/test";

test("policy governance cannot review or approve a saved definition while different edits are visible", async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem("corvo.intro.seen.v1", "1"));
  await page.goto("/");
  await page.getByLabel("Role", { exact: true }).selectOption("admin");
  await page.getByLabel("Password", { exact: true }).fill("corvo-demo");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await page.getByRole("link", { name: "Policy Reactor", exact: true }).click();
  await page.getByRole("button", { name: /5\.0.*active/ }).click();
  const version = "SAVED-STATE-REGRESSION";
  await page.getByLabel("New policy version").fill(version);
  await page.getByLabel("Policy effective date").fill("2026-11-01");
  const created = page.waitForResponse(r => r.url().endsWith("/api/policies") && r.request().method() === "POST");
  await page.getByRole("button", { name: "Clone selected as draft", exact: true }).click();
  expect((await created).status()).toBe(200);
  const editor = page.getByLabel("Policy DSL JSON", { exact: true });
  await expect(editor).toContainText(version);
  await page.getByLabel("Governance reason").fill("Checked the exact saved policy against the source");
  const original = await editor.inputValue();
  const changed = JSON.parse(original);
  changed.parameters.group_days = 11;
  await editor.fill(JSON.stringify(changed, null, 2));
  await expect(page.getByRole("button", { name: "Review policy", exact: true })).toBeDisabled();
  await expect(page.getByRole("button", { name: "Approve policy", exact: true })).toBeDisabled();
  await expect(page.getByText(/Unsaved editor changes/)).toBeVisible();
  const saved = page.waitForResponse(r => r.url().endsWith("/api/policies/" + version) && r.request().method() === "PUT");
  await page.getByRole("button", { name: "Save draft changes", exact: true }).click();
  expect((await saved).status()).toBe(200);
  await expect(page.getByRole("button", { name: "Review policy", exact: true })).toBeEnabled();
  await expect(page.getByRole("button", { name: "Approve policy", exact: true })).toBeDisabled();
  const reviewed = page.waitForResponse(r => r.url().endsWith("/review"));
  await page.getByRole("button", { name: "Review policy", exact: true }).click();
  expect((await reviewed).status()).toBe(200);
  await expect(page.getByRole("button", { name: "Approve policy", exact: true })).toBeEnabled();
  changed.parameters.group_days = 10;
  await editor.fill(JSON.stringify(changed, null, 2));
  await expect(page.getByRole("button", { name: "Approve policy", exact: true })).toBeDisabled();
  await expect(page.getByRole("button", { name: "Simulate selected policy", exact: true })).toBeDisabled();
});
